// Reuse native form captions in profile differences without loading form code.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from '@babel/parser';
import traverseModule from '@babel/traverse';

const traverse = traverseModule.default || traverseModule;
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.resolve(root, '../luci-app-trafira/htdocs/luci-static/resources/view/trafira');
const target = path.resolve(root, 'src/trafira/tabs/diagnostic/profileOptionLabels.ts');
const captions = { settings: {}, options: {} };
const settingsFiles = new Set(['settings.js', 'alice.js', 'gaming.js']);
for (const file of fs.readdirSync(source).sort()) {
  if (!file.endsWith('.js') || file === 'main.js') continue;
  const ast = parse(fs.readFileSync(path.join(source, file), 'utf8'), {
    sourceType: 'script', allowReturnOutsideFunction: true,
  });
  traverse(ast, { ForOfStatement(loop) {
    if (loop.node.right.type !== 'ArrayExpression') return;
    let definesOptions = false;
    loop.get('body').traverse({ CallExpression(inner) {
      if (['option', 'taboption'].includes(inner.node.callee.property?.name)) definesOptions = true;
    } });
    if (!definesOptions) return;
    for (const pair of loop.node.right.elements) {
      const [key, title] = pair?.type === 'ArrayExpression' ? pair.elements : [];
      if (key?.type === 'StringLiteral' && /^[a-z][a-z0-9_]*$/.test(key.value) && title?.callee?.name === '_' && title.arguments[0]?.type === 'StringLiteral')
        captions[settingsFiles.has(file) ? 'settings' : 'options'][key.value] = title.arguments[0].value;
    }
  }, CallExpression(call) {
    const { node } = call;
    const method = node.callee.property?.name;
    if (method === 'forEach' && node.callee.object?.type === 'ArrayExpression' && node.arguments[0]) {
      let definesOptions = false;
      call.get('arguments.0').traverse({ CallExpression(inner) {
        if (['option','taboption'].includes(inner.node.callee.property?.name)) definesOptions = true;
      } });
      if (definesOptions) for (const pair of node.callee.object.elements) {
        const [key, title] = pair?.type === 'ArrayExpression' ? pair.elements : [];
        if (key?.type === 'StringLiteral' && /^[a-z][a-z0-9_]*$/.test(key.value) && title?.callee?.name === '_' && title.arguments[0]?.type === 'StringLiteral')
          captions[settingsFiles.has(file) ? 'settings' : 'options'][key.value] = title.arguments[0].value;
      }
    }
    if (method !== 'option' && method !== 'taboption') return;
    const offset = method === 'taboption' ? 1 : 0;
    const kind = node.arguments[offset], key = node.arguments[offset + 1], title = node.arguments[offset + 2];
    if (['DummyValue', 'Button'].includes(kind?.property?.name)) return;
    if (key?.type !== 'StringLiteral' || !/^[a-z][a-z0-9_]*$/.test(key.value)) return;
    if (title?.type !== 'CallExpression' || title.callee.name !== '_' || title.arguments[0]?.type !== 'StringLiteral') return;
    captions[settingsFiles.has(file) ? 'settings' : 'options'][key.value] = title.arguments[0].value;
  } });
}
// These common keys describe several native section types, not just servers.
captions.options.label = 'Name';
Object.assign(captions.settings, {
  config_version: 'Configuration version',
  applied_migrations: 'Applied configuration migrations',
  shutdown_correctly: 'Clean shutdown state',
});
captions.options['.type'] = 'Section type';
captions.options.server = 'Server';
let code = '// Generated by scripts/generate-profile-labels.mjs from native LuCI captions.\n';
code += 'export function profileOptionLabels(): Record<string, Record<string, string>> {\n  return {\n';
for (const [group, labels] of Object.entries(captions)) {
  code += `    ${group}: {\n`;
  for (const key of Object.keys(labels).sort()) code += `      ${JSON.stringify(key)}: _(${JSON.stringify(labels[key])}),\n`;
  code += '    },\n';
}
code += '  };\n}\n';
// Keep generated source identical across Windows/Linux and editor formatting.
const { format } = await import('prettier');
code = await format(code, { parser: 'typescript', singleQuote: true, trailingComma: 'all' });
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== code) {
    throw new Error('Profile captions are out of date. Run node scripts/generate-profile-labels.mjs');
  }
} else fs.writeFileSync(target, code);
console.log(`Profile option captions: ${Object.values(captions).reduce((n, group) => n + Object.keys(group).length, 0)}`);
