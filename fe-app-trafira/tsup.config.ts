import { defineConfig } from 'tsup';
import fs from 'fs';
import path from 'path';
import { toLuciModule } from './scripts/luci-compaction.mjs';

export default defineConfig({
  entry: ['src/main.ts'],
  format: ['esm'], // пусть tsup генерит export {...}
  outDir: '../luci-app-trafira/htdocs/luci-static/resources/view/trafira',
  outExtension: () => ({ js: '.js' }),
  dts: false,
  clean: false,
  sourcemap: false,
  banner: {
    js: `// This file is autogenerated, please don't change manually \n"use strict";`,
  },
  esbuildOptions(options) {
    options.legalComments = 'none';
    // Public names are restored explicitly in toLuciModule().
    options.minifyWhitespace = true;
    options.minifySyntax = true;
    options.minifyIdentifiers = true;
  },
  onSuccess: () => {
    const outDir =
      '../luci-app-trafira/htdocs/luci-static/resources/view/trafira';
    const file = path.join(outDir, 'main.js');
    let code = fs.readFileSync(file, 'utf8');

    code = toLuciModule(code);

    fs.writeFileSync(file, code, 'utf8');
    console.log(`✅ Patched LuCI build: ${file}`);
  },
});
